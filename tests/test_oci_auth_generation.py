class TestOciAuthGeneration(unittest.TestCase):
    def test_challenge_regenerates_golden(self):
        pairs = [
            (b'AUTH_SESSKEY', _CAP_SESSKEY.encode(), 0),
            (b'AUTH_VFR_DATA', _CAP_SALT.encode(), auth._VERIFIER_TYPE_11G),
            (b'AUTH_GLOBALLY_UNIQUE_DBID\x00', auth._AUTH_GLOBALLY_UNIQUE_DBID, 0),
        ]
        self.assertEqual(
            auth._oci_auth_packet(pairs, auth._CHALLENGE_TRAILER), CHALLENGE_GOLDEN
        )

    def test_result_regenerates_golden(self):
        pairs = [(k, v, 0) for k, v in auth._RESULT_PARAMS]
        pairs.append((b'AUTH_SVR_RESPONSE', _CAP_SVR_RESPONSE.encode(), 0))
        self.assertEqual(
            auth._oci_auth_packet(pairs, auth._RESULT_TRAILER), RESULT_GOLDEN
        )

    def test_encode_kv_oci_empty_value(self):
        # An empty value is the ub4 length 0 with no data byte (then ub4 flags).
        self.assertEqual(
            auth.encode_kv_oci(b'K', b'', 0),
            struct.pack('<I', 1)
            + b'\x01K'
            + struct.pack('<I', 0)
            + struct.pack('<I', 0),
        )

    def test_encode_challenge_oci_end_to_end(self):
        # A freshly built challenge is a valid packet the length header matches.
        ch = auth.make_challenge(b'x' * 24, salt=b'y' * 10)
        pkt = auth.encode_challenge_oci(ch)
        self.assertEqual(struct.unpack('>H', pkt[:2])[0], len(pkt))
        self.assertIn(b'AUTH_SESSKEY', pkt)
        self.assertIn(b'AUTH_VFR_DATA', pkt)

    def test_encode_result_oci_end_to_end(self):
        pkt = auth.encode_result_oci(b'k' * 24, nonce=b'n' * 16)
        self.assertEqual(struct.unpack('>H', pkt[:2])[0], len(pkt))
        self.assertIn(b'AUTH_SVR_RESPONSE', pkt)
        self.assertIn(b'AUTH_NLS_LXCCALENDAR', pkt)


